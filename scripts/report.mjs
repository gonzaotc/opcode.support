// Renders data/results.json as REPORT.md.
import { readFileSync, writeFileSync } from 'node:fs';

const { checkedAt, opcodes, chains } = JSON.parse(readFileSync('data/results.json', 'utf8'));

const CELL = { supported: 'yes', unsupported: 'no', unknown: '?' };
const usd = (n) => (n >= 1e9 ? `$${(n / 1e9).toFixed(1)}B` : `$${Math.round(n / 1e6)}M`);
const names = (list) => (list.length ? list.map((c) => c.name).join(', ') : 'none');

const out = [];
out.push('# EVM opcode support, top 30 chains by TVL');
out.push('');
out.push(`Checked ${checkedAt}. Generated by \`scripts/probe.mjs\`, do not edit by hand.`);
out.push('');
out.push(
	'Every check is a read-only `eth_call` simulation, so no transaction is ever sent and no gas is spent.',
);
out.push(
	'A verdict is only recorded when at least two independently calibrated RPC endpoints agree. Percentages count confirmed verdicts only.',
);
out.push('');

out.push('## Summary');
out.push('');
out.push('| opcode | byte | fork | EIP | supported | unsupported | unconfirmed | support |');
out.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
const buckets = {};
for (const opcode of opcodes) {
	const group = { supported: [], unsupported: [], unknown: [] };
	for (const chain of chains) group[chain.opcodes[opcode.name].status].push(chain);
	buckets[opcode.name] = group;
	const confirmed = group.supported.length + group.unsupported.length;
	const pct = confirmed ? `${Math.round((group.supported.length / confirmed) * 100)}%` : 'n/a';
	out.push(
		`| \`${opcode.name}\` | \`${opcode.byte}\` | ${opcode.fork} | ${opcode.eip} | ${group.supported.length} | ${group.unsupported.length} | ${group.unknown.length} | **${pct}** of ${confirmed} confirmed |`,
	);
}
out.push('');

for (const opcode of opcodes) {
	const group = buckets[opcode.name];
	out.push(`## ${opcode.name} (\`${opcode.byte}\`, ${opcode.fork}, ${opcode.eip})`);
	out.push('');
	out.push(`- **Supported (${group.supported.length}):** ${names(group.supported)}`);
	out.push(`- **Not supported (${group.unsupported.length}):** ${names(group.unsupported)}`);
	out.push(`- **Unconfirmed (${group.unknown.length}):** ${names(group.unknown)}`);
	out.push('');
}

out.push('## Matrix');
out.push('');
out.push(`| # | chain | chain id | TVL | ${opcodes.map((o) => o.name).join(' | ')} | witnesses |`);
out.push(`| --- | --- | --- | --- | ${opcodes.map(() => '---').join(' | ')} | --- |`);
chains.forEach((chain, i) => {
	const cells = opcodes.map((o) => CELL[chain.opcodes[o.name].status]);
	const witnesses = chain.witnesses.filter((w) => w.calibrated).length;
	out.push(
		`| ${i + 1} | ${chain.name} | ${chain.chainId} | ${usd(chain.tvlUsd)} | ${cells.join(' | ')} | ${witnesses} |`,
	);
});
out.push('');

const unresolved = chains.filter((c) => opcodes.some((o) => c.opcodes[o.name].status === 'unknown'));
if (unresolved.length) {
	out.push('## Unconfirmed chains');
	out.push('');
	out.push('| chain | reason | detail |');
	out.push('| --- | --- | --- |');
	for (const chain of unresolved) {
		const verdict = opcodes.map((o) => chain.opcodes[o.name]).find((v) => v.status === 'unknown');
		const rejections = chain.witnesses
			.filter((w) => !w.calibrated)
			.flatMap((w) => Object.values(w.rejected ?? {}))
			.filter((v, i, all) => all.indexOf(v) === i)
			.slice(0, 2)
			.join('; ');
		out.push(`| ${chain.name} | ${verdict.confidence} | ${rejections || 'see data/results.json'} |`);
	}
	out.push('');
}

out.push('## Method');
out.push('');
out.push('For each opcode the probe asks a node to execute a minimal bytecode snippet that supplies the');
out.push("opcode's stack inputs with `PUSH0`, so a clean run means supported and a rejection means unsupported.");
out.push('');
out.push('Two read-only ways to get a node to execute that snippet are tried, in order:');
out.push('');
out.push('1. `eth_call` with a state override placing the snippet as code at a dummy address');
out.push('2. `eth_call` with no `to`, so the snippet is treated as contract creation code');
out.push('');
out.push('Each endpoint is calibrated before its answers are used. `STOP` (`0x00`) must succeed and `0x0c`,');
out.push('undefined in every fork, must fail. Endpoints that pass neither strategy are excluded, which is');
out.push('what keeps endpoints that silently ignore state overrides, or skip execution entirely, out of the');
out.push('data. The rejection wording from the negative control is reused as that endpoint\'s fingerprint for');
out.push('recognising a genuine opcode rejection.');
out.push('');
out.push('Failures that are not attributable to the EVM, such as provider rate limits and plan quotas, are');
out.push('recorded as unconfirmed rather than counted as unsupported.');
out.push('');
out.push('## Limits');
out.push('');
out.push('- `PREVRANDAO` and `DIFFICULTY` share byte `0x44`, so availability cannot distinguish them.');
out.push('- Prague adds no opcode, so its support cannot be probed this way at all.');
out.push('- On chains whose native toolchain compiles to a different VM, this measures the EVM execution path');
out.push('  the RPC exposes, which is not necessarily what a natively compiled contract targets.');
out.push('- Availability is not semantics. Gas costs and edge-case behaviour are out of scope here.');
out.push('');

writeFileSync('REPORT.md', `${out.join('\n')}\n`);
console.log(`wrote REPORT.md (${chains.length} chains, ${opcodes.length} opcodes)`);
