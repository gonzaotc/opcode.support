// Renders data/results.json as REPORT.md.
import { readFileSync, writeFileSync } from 'node:fs';

const { checkedAt, opcodes, chains } = JSON.parse(readFileSync('data/results.json', 'utf8'));

const CELL = { supported: 'yes', unsupported: 'no', unknown: '?' };
const usd = (n) => (n >= 1e9 ? `$${(n / 1e9).toFixed(1)}B` : `$${Math.round(n / 1e6)}M`);
const names = (chains) => (chains.length ? chains.map((c) => c.name).join(', ') : 'none');
const calibrated = (chain) => chain.witnesses.filter((w) => w.calibrated).length;

const table = (headers, rows) =>
	[`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

const groupsByOpcode = new Map(
	opcodes.map((opcode) => {
		const group = { supported: [], unsupported: [], unknown: [] };
		for (const chain of chains) group[chain.opcodes[opcode.name].status].push(chain);
		return [opcode.name, group];
	}),
);

const summary = table(
	['opcode', 'byte', 'fork', 'EIP', 'supported', 'unsupported', 'unconfirmed', 'support'],
	opcodes.map((opcode) => {
		const { supported, unsupported, unknown } = groupsByOpcode.get(opcode.name);
		const confirmed = supported.length + unsupported.length;
		const pct = confirmed ? `${Math.round((supported.length / confirmed) * 100)}%` : 'n/a';
		return [
			`\`${opcode.name}\``,
			`\`${opcode.byte}\``,
			opcode.fork,
			opcode.eip,
			supported.length,
			unsupported.length,
			unknown.length,
			`**${pct}** of ${confirmed} confirmed`,
		];
	}),
);

const perOpcode = opcodes
	.map((opcode) => {
		const { supported, unsupported, unknown } = groupsByOpcode.get(opcode.name);
		return [
			`## ${opcode.name} (\`${opcode.byte}\`, ${opcode.fork}, ${opcode.eip})`,
			'',
			`- **Supported (${supported.length}):** ${names(supported)}`,
			`- **Not supported (${unsupported.length}):** ${names(unsupported)}`,
			`- **Unconfirmed (${unknown.length}):** ${names(unknown)}`,
		].join('\n');
	})
	.join('\n\n');

const matrix = table(
	['#', 'chain', 'chain id', 'TVL', ...opcodes.map((o) => o.name), 'witnesses'],
	chains.map((chain, i) => [
		i + 1,
		chain.name,
		chain.chainId,
		usd(chain.tvlUsd),
		...opcodes.map((o) => CELL[chain.opcodes[o.name].status]),
		calibrated(chain),
	]),
);

const unresolved = chains.filter((c) => opcodes.some((o) => c.opcodes[o.name].status === 'unknown'));
const unconfirmed = unresolved.length
	? [
			'## Unconfirmed chains',
			'',
			table(
				['chain', 'reason', 'detail'],
				unresolved.map((chain) => {
					const verdict = opcodes.map((o) => chain.opcodes[o.name]).find((v) => v.status === 'unknown');
					const rejections = [
						...new Set(chain.witnesses.filter((w) => !w.calibrated).flatMap((w) => Object.values(w.rejected ?? {}))),
					].slice(0, 2);
					return [chain.name, verdict.confidence, rejections.join('; ') || 'see data/results.json'];
				}),
			),
			'',
		].join('\n')
	: '';

writeFileSync(
	'REPORT.md',
	`# EVM opcode support, top 30 chains by TVL

Checked ${checkedAt}. Generated by \`scripts/probe.mjs\`, do not edit by hand.

Every check is a read-only \`eth_call\` simulation, so no transaction is ever sent and no gas is spent.
A verdict is only recorded when at least two independently calibrated RPC endpoints agree.
Percentages count confirmed verdicts only.

## Summary

${summary}

${perOpcode}

## Matrix

${matrix}

${unconfirmed}
## Method

For each opcode the probe asks a node to execute a minimal bytecode snippet that supplies the
opcode's stack inputs with \`PUSH0\`, so a clean run means supported and a rejection means unsupported.

Two read-only ways to get a node to execute that snippet are tried, in order:

1. \`eth_call\` with a state override placing the snippet as code at a dummy address
2. \`eth_call\` with no \`to\`, so the snippet is treated as contract creation code

Each endpoint is calibrated before its answers are used. \`STOP\` (\`0x00\`) must succeed and \`0x0c\`,
undefined in every fork, must fail. Endpoints passing neither strategy are excluded, which is what
keeps endpoints that silently ignore state overrides, or skip execution entirely, out of the data.

Failures that are not attributable to the EVM, such as provider rate limits and plan quotas, are
recorded as unconfirmed rather than counted as unsupported.

## Limits

- \`PREVRANDAO\` and \`DIFFICULTY\` share byte \`0x44\`, so availability cannot distinguish them.
- Prague adds no opcode, so its support cannot be probed this way at all.
- On chains whose native toolchain compiles to a different VM, this measures the EVM execution path
  the RPC exposes, which is not necessarily what a natively compiled contract targets.
- Availability is not semantics. Gas costs and edge-case behaviour are out of scope here.
`,
);
console.log(`wrote REPORT.md (${chains.length} chains, ${opcodes.length} opcodes)`);
